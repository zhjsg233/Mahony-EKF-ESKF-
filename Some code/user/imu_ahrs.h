/*********************************************************************************************************************
* 文件名称          imu_ahrs
* 公司名称          用户工程
* 编译平台          IAR 9.40.1
* 芯片平台          CYT4BB
*
* 功能说明          IMU660RB 姿态解算模块(按 IMU_AHRS_MODE 宏选择算法)
*                   - 0 = 曼哈尼(Mahony)互补滤波; 1 = 四元数EKF;
*                   - 2 = ESKF(误差状态卡尔曼, 10态: 姿态+零漂+二维速度/位置, 角速度积分+加速度/轮速观测)
*                   - 均为 6 轴(加速度计 + 陀螺仪, 无磁力计), 航向 yaw 为陀螺积分, 会缓慢漂移
*                   - 1kHz 采样率(PIT 1ms 中断驱动)
*                   - 上电加速度初始角度对准 + 陀螺仪零偏标定
*                   - 安装方向修正: 见 AXIS_ACC_* 与 AXIS_GYR_* 宏
*                   - 约定: pitch 抬头为正, roll 右侧下压为正, yaw 俯视顺时针(右转)为正
********************************************************************************************************************/

#ifndef _imu_ahrs_h_
#define _imu_ahrs_h_

#include "zf_common_typedef.h"

#define DEG2RAD (0.0174532925199f)      // 度转弧度
#define RAD2DEG (57.2957795131f)        // 弧度转度

//====================================================================算法选择====================================================================
// 姿态解算算法: 0 = 互补滤波(Mahony), 1 = 四元数EKF, 2 = ESKF(误差状态卡尔曼)
#define IMU_AHRS_MODE   (0)
//====================================================================算法选择====================================================================

//====================================================================安装方向修正====================================================================
// 将传感器原始输出转换为机体坐标(NED: X前 / Y右 / Z下)。
//   · 加速度计: 传感器输出的是"比力"(静止时下压轴读数 -1g), 滤波器需要"重力方向"(下压轴 +1g),
//               故加速度三轴取反 → 水平静止时 ACC 显示 (0,0,1)。
//   · 陀螺仪:   输出已是标准右手系角速度(绕轴右旋为正), 无需取反。
// 若实测某轴仍反, 只需把对应轴的宏改为 +1 或 -1。
#define AXIS_ACC_X_DIR   (-1)           // 1 或 -1
#define AXIS_ACC_Y_DIR   (-1)           // 1 或 -1
#define AXIS_ACC_Z_DIR   (-1)           // 1 或 -1
#define AXIS_GYR_X_DIR   ( 1)           // 1 或 -1
#define AXIS_GYR_Y_DIR   ( 1)           // 1 或 -1
#define AXIS_GYR_Z_DIR   ( 1)           // 1 或 -1
//====================================================================安装方向修正====================================================================

//====================================================IMU 姿态全局变量====================================================
extern float imu_roll_deg;                          // 横滚角(度), 右侧下压为正
extern float imu_pitch_deg;                         // 俯仰角(度), 抬头为正
extern float imu_yaw_deg;                           // 航向角(度), 俯视顺时针(右转)为正
extern float imu_quat[4];                           // 四元数 (w,x,y,z) 机体->NED
extern float imu_acc_g[3];                          // 机体系加速度(g), 1ms 更新, 静止水平约 (0,0,1)
extern float imu_gyro_dps[3];                       // 机体系角速度(°/s), 1ms 更新
extern float eskf_r_eff;                            // ESKF 有效加速度观测噪声R(g², 显示用)
extern float imu_eskf_bias[3];                      // ESKF 在线估计的残余陀螺零偏(rad/s, 显示用)
extern volatile uint32 imu_ahrs_update_count;       // 1kHz 采样计数(主循环1kHz块内自增)
extern volatile uint8  g_imu_tick_pending;          // 1kHz 节拍标志: ISR置位, 主循环清零并做姿态+惯导
// 中断采样的IMU原始数据(1ms准时), 主循环取来做重计算
extern volatile float imu_smp_gx, imu_smp_gy, imu_smp_gz;
extern volatile float imu_smp_ax, imu_smp_ay, imu_smp_az;
//====================================================IMU 姿态全局变量====================================================

//====================================================IMU 姿态函数====================================================
void imu_ahrs_init  (void);                         // 等待2s稳定后, 上电零偏 + 加速度初始对准(阻塞约3s, 需保持静止)
void imu_ahrs_read  (float *gx, float *gy, float *gz,   // 陀螺 rad/s(已做安装方向修正)
                     float *ax, float *ay, float *az);  // 加速度 g(已做安装方向修正)
void imu_ahrs_update(float gx, float gy, float gz,   // 陀螺仪 rad/s(内部自动减去零偏)
                     float ax, float ay, float az,   // 加速度 g
                     float dt);                      // 采样间隔(秒), 1kHz 用 0.001f
void imu_ahrs_get_euler(void);                       // 由四元数重新计算 imu_roll_deg / imu_pitch_deg / imu_yaw_deg
//====================================================IMU 姿态函数====================================================

//====================================================惯导(10态ESKF: 速度/位置)====================================================
// 速度/位置已并入 10 态 ESKF 误差状态 [δθ(3), δb(3), δv(2), δp(2)], 名义世界系水平位置/速度由 ESKF 每拍写入:
//   imu_nav_vx/vy: 名义速度(m/s, 世界系), 由比力积分 + 轮速观测修正
//   imu_nav_x/y  : 名义位置(m, 世界系), 由速度积分(纯航迹推算, 暂无明显位置测量源)
// 速度观测只修正速度与位置(内部强制 δθ、δb 增益行为零), 姿态与零漂仅由加速度观测修正
extern float imu_nav_x, imu_nav_y;                      // 位置(m)
extern float imu_nav_vx, imu_nav_vy;                    // 速度(m/s)

#define NAV_LEVER_ARM_Z     (0.1f)                   // 杠臂: 轮速观测点到IMU的z向距离(m), 轮在(0,0,0), IMU在(0,0,-0.1)
#define NAV_LEVER_ARM_ENABLE (1)                     // 1=开杠臂补偿; 0=关闭(滤波预测补偿和观测显示都不补偿)
void imu_nav_init      (void);                          // 惯导(ESKF速度/位置块)初始化: 清零位置/速度, 重置协方差分块初值

// 速度观测接口: 世界系vx/vy(需按航向分解) + 机体角速度wx/wy(杠臂), 500Hz 调用
void eskf_vel_update(float vx_meas, float vy_meas, float wx, float wy);
// 位置观测接口(预留): 有外部位置测量(GPS/信标/摄像头等)时调用, 当前工程暂无测量源
void eskf_pos_update(float x_meas, float y_meas);

// 速度观测 R: 固定 = 1e-4(轮速 1cm/s 精度), 不做自适应。
// 新息门限: 速度观测与预测相差超过 ESKF_VEL_INNOV_GATE_MPS(10m/s) 时拒绝本次观测(抗打滑/离群)。
// 说明: 之前试过教科书 IAE(新息协方差匹配 R̂=C_y−H·P⁻·Hᵀ), 但新息把"速度误差偏置"误当噪声
//       → 收敛慢/发散, 已删除, 轮速观测固定R直接修正
extern float nav_r_vel;                             // 当前生效的速度观测噪声方差((m/s)², 固定 ESKF_R_VEL)
// 杠臂补偿后的观测速度(显示/打印用): v_P = v_B + ω×(r_P−r_B), 由 main 每拍计算
extern float imu_nav_obs_vx, imu_nav_obs_vy;        // 世界系, 单位 m/s
//====================================================惯导(10态ESKF: 速度/位置)====================================================

#endif
